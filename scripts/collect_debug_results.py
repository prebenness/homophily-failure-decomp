"""Collect baseline-validation debug results into a tracked summary table.

Reads every results/debug/*.json produced by debug_baseline.py, re-verdicts
each run against the CURRENT manifests/reference_numbers.yaml (so the table
never carries stale gate info), and writes results/debug_baseline.md.
"""

from __future__ import annotations

import json
from pathlib import Path

import yaml

REPO_ROOT = Path(__file__).resolve().parents[1]
DATASET_ORDER = ["pubmed", "ogbn-arxiv", "roman-empire", "amazon-ratings", "arxiv-year"]
MODEL_ORDER = ["mlp", "gcn", "graphsage-mean", "h2gcn", "gpr-gnn", "linkx", "acm-gcn", "gat"]


def reverdict(row: dict, refs: dict) -> dict:
    """Recompute reference comparison and verdict from the stored test metric."""
    anchor = refs["anchors"].get(row["dataset"], {}).get(row["model"])
    margin = refs["gate_margin_points"]
    test_pct = row["test_metric_pct"]
    if anchor is None:
        flag = test_pct <= row["majority_class_pct"] + 5.0
        row.update(
            reference_pct=None,
            deviation_pct=None,
            grade="unanchored",
            verdict="sanity-FLAG" if flag else "sanity-ok (becomes reference)",
        )
    else:
        deviation = test_pct - anchor["value"]
        row.update(
            reference_pct=anchor["value"],
            deviation_pct=round(deviation, 2),
            grade="anchored",
            verdict="FLAG" if abs(deviation) > margin else "ok",
        )
    return row


def main() -> None:
    refs = yaml.safe_load(
        (REPO_ROOT / "manifests" / "reference_numbers.yaml").read_text(encoding="utf-8")
    )
    rows = []
    for path in sorted((REPO_ROOT / "results" / "debug").glob("*.json")):
        rows.append(reverdict(json.loads(path.read_text(encoding="utf-8")), refs))
    rows.sort(
        key=lambda r: (
            DATASET_ORDER.index(r["dataset"]),
            MODEL_ORDER.index(r["model"]),
            r["seed"],
        )
    )

    lines = [
        "# Baseline validation debug results",
        "",
        "ERM-only debug runs (standard whole-test metric, no local-homophily",
        "data collected). Generated by `scripts/collect_debug_results.py` from",
        "`results/debug/`; gate rules and references in",
        "`manifests/reference_numbers.yaml`.",
        "",
        "| dataset | model | split | seed | test % | ref % | dev | grade | verdict | best epoch | epochs | seconds | code |",
        "|---|---|---|---|---|---|---|---|---|---|---|---|---|",
    ]
    for r in rows:
        ref = "-" if r["reference_pct"] is None else f"{r['reference_pct']:.2f}"
        dev = "-" if r["deviation_pct"] is None else f"{r['deviation_pct']:+.1f}"
        lines.append(
            f"| {r['dataset']} | {r['model']} | {r['split']} | {r['seed']} "
            f"| {r['test_metric_pct']:.2f} | {ref} | {dev} | {r['grade']} "
            f"| {r['verdict']} | {r['best_epoch']} | {r['epochs_run']} "
            f"| {r['train_seconds']:.0f} | {r['code_version'][:8]} |"
        )
    out = REPO_ROOT / "results" / "debug_baseline.md"
    out.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"{len(rows)} cells -> {out}")


if __name__ == "__main__":
    main()
