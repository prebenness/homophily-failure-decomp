"""Load a dataset registry and verify its fixed-input registration.

Writes, per dataset:
- manifests/datasets/<name>.json  (git-tracked stats + checksums)
- artifacts/manifests/<name>.npz  (node-level arrays: h_v, bins, splits)
and a combined human-readable summary at results/dataset_stats.md.

By default, regenerated values must match the tracked manifests. The binary
fixed arrays are then written below ``artifacts/``. Replacing the tracked
registration requires ``--update-registration``.

Usage:
    python scripts/compute_dataset_stats.py --verify
    python scripts/compute_dataset_stats.py --update-registration
"""

from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(REPO_ROOT / "src"))

import yaml  # noqa: E402

from hfd.datasets import DATASET_NAMES, load_dataset  # noqa: E402
from hfd.stats import (  # noqa: E402
    attach_checksums,
    build_arrays,
    compute_dataset_stats,
    save_arrays,
)


def write_text_lf(path: Path, text: str) -> None:
    with path.open("w", encoding="utf-8", newline="\n") as handle:
        handle.write(text)


def summary_row(stats: dict) -> dict:
    lh = stats["local_homophily"]
    return {
        "dataset": stats["dataset"],
        "nodes": stats["graph"]["num_nodes"],
        "edges (simple)": stats["graph"]["num_undirected_simple_edges"],
        "classes": stats["graph"]["num_classes"],
        "features": stats["graph"]["feature_dim"],
        "mean h_v": f"{lh['mean_h']:.3f}",
        "direction": lh["direction"],
        "tail": lh["tail"]["interval"],
        "tail frac": f"{lh['tail']['fraction_of_eligible']:.3f}",
        "undef h_v": lh["n_undefined_h"],
        "splits": len(stats["splits"]),
        "seeds": len(stats["training_seeds"]),
    }


def summary_markdown(
    rows: list[dict], all_stats: list[dict], manifest_dir: str
) -> str:
    lines = [
        "# Dataset fixed-input summary",
        "",
        "Generated by `scripts/compute_dataset_stats.py`. Full details per",
        f"dataset in `{manifest_dir}/<name>.json`.",
        "",
    ]
    headers = list(rows[0].keys())
    lines.append("| " + " | ".join(headers) + " |")
    lines.append("|" + "|".join("---" for _ in headers) + "|")
    for row in rows:
        lines.append("| " + " | ".join(str(row[h]) for h in headers) + " |")

    lines += ["", "## Local-homophily bins (post-merge)", ""]
    for stats in all_stats:
        lh = stats["local_homophily"]
        lines.append(f"### {stats['dataset']}")
        lines.append("")
        lines.append("| bin | count | fraction | tail | top classes (count) |")
        lines.append("|---|---|---|---|---|")
        for mb in lh["merged_bins"]:
            tail = "yes" if mb["is_tail"] else ""
            comp = sorted(
                mb["class_composition"].items(), key=lambda kv: -kv[1]
            )
            shown = ", ".join(f"{c}: {n}" for c, n in comp[:5])
            if len(comp) > 5:
                shown += f", ... ({len(comp)} classes)"
            lines.append(
                f"| {mb['interval']} | {mb['count']} | "
                f"{mb['fraction_of_eligible']:.4f} | {tail} | {shown} |"
            )
        if lh["merge_history"]:
            lines.append("")
            lines.append("Merges: " + "; ".join(lh["merge_history"]))
        lines.append("")
    return "\n".join(lines)


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--datasets",
        nargs="+",
        help="subset to process; defaults to the datasets listed in --config",
    )
    parser.add_argument("--config", default=str(REPO_ROOT / "configs" / "datasets.yaml"))
    mode = parser.add_mutually_exclusive_group()
    mode.add_argument(
        "--verify",
        action="store_true",
        help=(
            "regenerate fixed inputs and verify the tracked registration "
            "(the default)"
        ),
    )
    mode.add_argument(
        "--update-registration",
        action="store_true",
        help="replace tracked manifests after an intentional protocol change",
    )
    args = parser.parse_args()

    config = yaml.safe_load(Path(args.config).read_text(encoding="utf-8"))
    registered_datasets = config.get("datasets")
    if not isinstance(registered_datasets, list) or not registered_datasets:
        raise ValueError(f"{args.config}: datasets must be a non-empty list")
    if len(registered_datasets) != len(set(registered_datasets)):
        raise ValueError(f"{args.config}: datasets contains duplicates")
    unknown = sorted(set(registered_datasets) - set(DATASET_NAMES))
    if unknown:
        raise ValueError(
            f"{args.config}: unknown dataset loader(s): {', '.join(unknown)}"
        )
    selected_datasets = args.datasets or registered_datasets
    outside_registry = sorted(set(selected_datasets) - set(registered_datasets))
    if outside_registry:
        raise ValueError(
            "selected datasets are absent from the registry: "
            + ", ".join(outside_registry)
        )
    data_root = REPO_ROOT / config["data_root"]
    array_dir = REPO_ROOT / config["array_dir"]
    manifest_dir = REPO_ROOT / config["manifest_dir"]
    manifest_dir.mkdir(parents=True, exist_ok=True)

    rows, all_stats = [], []
    for name in selected_datasets:
        print(f"=== {name} ===", flush=True)
        bundle = load_dataset(name, data_root)
        stats, groups = compute_dataset_stats(bundle)
        arrays = build_arrays(bundle, groups)
        attach_checksums(stats, arrays)

        manifest_path = manifest_dir / f"{name}.json"
        if args.update_registration:
            write_text_lf(manifest_path, json.dumps(stats, indent=2) + "\n")
        else:
            if not manifest_path.is_file():
                raise FileNotFoundError(
                    f"Registered dataset manifest is missing: {manifest_path}. "
                    "Use --update-registration only for an intentional "
                    "registration change."
                )
            registered = json.loads(manifest_path.read_text(encoding="utf-8"))
            serialised_stats = json.loads(json.dumps(stats))
            if registered != serialised_stats:
                raise RuntimeError(
                    f"{name}: regenerated fixed inputs differ from the tracked "
                    "dataset manifest. Inspect the data source and software "
                    "versions before considering --update-registration."
                )
        save_arrays(arrays, array_dir / f"{name}.npz")
        print(json.dumps(summary_row(stats), indent=2), flush=True)
        rows.append(summary_row(stats))
        all_stats.append(stats)

    if selected_datasets == registered_datasets:
        summary_path = REPO_ROOT / config.get(
            "summary_path", "results/dataset_stats.md"
        )
        summary_path.parent.mkdir(parents=True, exist_ok=True)
        rendered = summary_markdown(rows, all_stats, config["manifest_dir"])
        if args.update_registration:
            write_text_lf(summary_path, rendered)
            print(f"Summary written to {summary_path.relative_to(REPO_ROOT)}")
        else:
            current = summary_path.read_text(encoding="utf-8")
            if current != rendered:
                raise RuntimeError(
                    f"{summary_path.relative_to(REPO_ROOT)} differs from the "
                    "registered dataset summary"
                )
            print(f"Verified {summary_path.relative_to(REPO_ROOT)}")


if __name__ == "__main__":
    main()
